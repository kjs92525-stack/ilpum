# 근무표 하루 인쇄(2026-11-08): '하루 인쇄' → 하루치 A4 가로 1장, 날짜 넘기기, 메모 숫자·금액 없음, 포지션 색·당일알바 진한 갈색·큰 배경색 없음, 여백 12mm, PDF 1장 (체험 모드)
import asyncio, re, sys
from playwright.async_api import async_playwright
async def main():
  ok=True
  def chk(n,c,x=''):
    nonlocal ok; ok&=bool(c); print('OK  ' if c else 'FAIL',n,x)
  async with async_playwright() as p:
    b=await p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1194/chrome-linux/chrome')
    pg=await b.new_page(viewport={'width':1400,'height':950}); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    await pg.route('**/*', lambda r: r.abort() if 'supabase' in r.request.url else r.continue_())
    await pg.goto('http://localhost:8765/ilpum-schedule.html'); await pg.evaluate("localStorage.clear(); localStorage.setItem('ilpum-fr-conf','{\"mode\":\"local\"}')"); await pg.reload(); await pg.wait_for_timeout(1200)
    t=await pg.evaluate("ds(new Date())"); t2=await pg.evaluate("ds(addDays(new Date(),1))")
    await pg.evaluate(f"put('spot','sp1',{{id:'sp1',date:'{t}',name:'박명순',pos:APP.D.positions[0].name,memo:'6.5'}})")
    await pg.click('[data-a="view"][data-v="cards"]'); await pg.wait_for_timeout(300)
    chk('스케줄 화면엔 메모 숫자 보임', '6.5' in await pg.inner_text('.cards'))
    await pg.click('[data-a="pmode"]'); await pg.wait_for_timeout(500)
    chk('하루 인쇄: 오늘 1장', await pg.locator('#pm .pmpage').count()==1 and await pg.input_value('#pmDate')==t)
    txt=await pg.inner_text('#pm .pmpages')
    chk('이름만(메모 숫자·금액 없음)', '박명순' in txt and '6.5' not in txt, txt[:120])
    pc=await pg.evaluate("getComputedStyle(document.querySelector('#pm .pml')).color")
    chk('포지션 이름은 화면처럼 색', pc not in ('rgb(0, 0, 0)','rgb(17, 17, 17)'), pc)
    lum=await pg.evaluate("(()=>{const c=getComputedStyle(document.querySelector('#pm .pmc.sp')).color.match(/\\d+/g).map(Number);return .299*c[0]+.587*c[1]+.114*c[2]})()")
    chk('당일알바 이름은 흑백 인쇄에서도 진하게(밝기 낮음)', lum<90, lum)
    bgs=await pg.evaluate("[...new Set([...document.querySelectorAll('#pm .pmpage *')].map(e=>getComputedStyle(e).backgroundColor))]")
    chk('배경색 없음(잉크 아낌)', all(x in ('rgba(0, 0, 0, 0)',) for x in bgs), bgs)
    fit=await pg.evaluate("(()=>{const g=document.querySelector('#pm .pmgrid');return g.scrollHeight<=g.clientHeight+1})()")
    chk('종이 안에 들어감', fit)
    await pg.click('[data-pmd="1"]'); await pg.wait_for_timeout(250)
    chk('다음 날로 넘김', await pg.input_value('#pmDate')==t2 and '박명순' not in await pg.inner_text('#pm .pmpages'))
    await pg.click('[data-pmd="-1"]'); await pg.wait_for_timeout(250)
    if len(sys.argv)>1: await pg.locator('#pm .pmpage').screenshot(path=sys.argv[1])
    await pg.emulate_media(media='print')
    vis=await pg.evaluate("[getComputedStyle(document.querySelector('.app')).display, getComputedStyle(document.querySelector('.pmbar')).display]")
    chk('인쇄할 땐 종이만', vis==['none','none'], vis)
    pdf=await pg.pdf(prefer_css_page_size=True, print_background=True)
    n=len(re.findall(rb'/Type\s*/Page[^s]', pdf)); mb=re.search(rb'/MediaBox\s*\[\s*0 0 ([\d.]+) ([\d.]+)',pdf)
    chk('PDF 1장·A4 가로', n==1 and mb and float(mb.group(1))>float(mb.group(2)), (n, mb and mb.groups()))
    if len(sys.argv)>2: open(sys.argv[2],'wb').write(pdf)
    await pg.emulate_media(media='screen')
    await pg.click('[data-pmx]'); await pg.wait_for_timeout(200)
    chk('닫으면 원래 화면', not await pg.evaluate("document.body.classList.contains('pm-on')"))
    chk('오류 없음', not errs, errs); await b.close()
  print('전체 OK' if ok else '실패 있음')
asyncio.run(main())
